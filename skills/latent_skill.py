"""
QAG_MemBrain — LatentSkill Integration
=======================================
Based on: arxiv 2606.06087 — LatentSkill: From In-Context Textual Skills
to In-Weight Latent Skills for LLM Agents (SJTU / Sun Yat-sen / OPPO, 2025)

Core contribution:
  Textual skill descriptions → LoRA adapters via pretrained hypernetwork.
  Skill knowledge lives in WEIGHT SPACE, not context window.
  Result: 64.1% fewer prefill tokens, 21.4 point ALFWorld improvement.

How this replaces the existing SKILL_ADAPTERS array in rev_ike.ts:

BEFORE (plaintext, context-overhead):
  SKILL_ADAPTERS = [
    { patterns: [/gazebo/i], insight: fn, action: fn },  # in-context skill
    ...
  ]
  Problem: skill text injected into every prompt = token overhead + exposure.

AFTER (LatentSkill, weight-space):
  skill_registry.load("service-demand")  # loads LoRA adapter
  model.merge_adapter()                  # zero-overhead inference
  model.unload_adapter()                 # clean swap

Additional finding from paper:
  Skill LoRAs form structured semantic geometry — composable via
  parameter-space arithmetic. Two skills can be MERGED without retraining.
  This enables novel task types from combinations of existing adapters.
"""

from __future__ import annotations
from dataclasses import dataclass, field
from typing import Any
import os, json, hashlib


# ─── Skill descriptor ────────────────────────────────────────────────
# This is the INPUT to the hypernetwork.
# Human-readable textual skill → hypernetwork → LoRA adapter weights.
@dataclass
class SkillDescriptor:
    """
    Textual skill description fed to the hypernetwork.
    The hypernetwork (pretrained) converts this to LoRA A/B matrices.
    """
    skill_id:        str
    name:            str
    description:     str    # Natural language — what the skill does
    trigger_phrases: list[str]  # When to activate
    output_schema:   dict   # What the model should return when skill active
    theme:           str    # Philosophical theme for Rev.Ike mapping
    lora_rank:       int = 16   # LoRA rank — higher = more expressive
    lora_alpha:      float = 32.0

    def to_skill_text(self) -> str:
        """Format for hypernetwork input — the 'textual skill' representation."""
        return (
            f"Skill: {self.name}\n"
            f"Description: {self.description}\n"
            f"Triggers: {', '.join(self.trigger_phrases)}\n"
            f"Output: {json.dumps(self.output_schema)}\n"
            f"Theme: {self.theme}"
        )

    def skill_hash(self) -> str:
        """Deterministic ID for caching the generated LoRA adapter."""
        return hashlib.sha256(self.to_skill_text().encode()).hexdigest()[:16]


# ─── LoRA adapter (generated by hypernetwork) ─────────────────────────
@dataclass
class LoRAAdapter:
    """
    Weight-space skill. Generated once by hypernetwork, cached locally.
    Plug-and-play: merge → infer → unload. Zero context overhead.
    """
    skill_id:     str
    skill_hash:   str
    # In production: actual LoRA A/B matrices (torch.Tensor)
    # Here: metadata stubs — replace with real tensors from HF
    lora_A:       Any = None   # shape: (rank, input_dim)
    lora_B:       Any = None   # shape: (output_dim, rank)
    rank:         int = 16
    alpha:        float = 32.0
    adapter_path: str = ""     # HF Hub path or local cache path


# ─── Skill registry ───────────────────────────────────────────────────
# Manages textual skills → LoRA adapters lifecycle.
# Replaces SKILL_ADAPTERS plaintext array in rev_ike.ts.
class SkillRegistry:
    """
    Manages the skill adapter lifecycle:
      register(descriptor) → hypernetwork → LoRAAdapter → cache
      load(skill_id)       → merge adapter into model (zero token cost)
      compose(ids)         → parameter-space arithmetic for novel tasks
      unload(skill_id)     → clean adapter removal
    """

    def __init__(
        self,
        cache_dir:        str = "./skill_cache",
        hypernetwork_url: str | None = None,
    ):
        self.cache_dir        = cache_dir
        self.hypernetwork_url = hypernetwork_url or os.environ.get("LATENTSKILL_HN_URL")
        self.registry:  dict[str, SkillDescriptor] = {}
        self.adapters:  dict[str, LoRAAdapter]     = {}
        self.active:    list[str]                   = []
        os.makedirs(cache_dir, exist_ok=True)

    def register(self, descriptor: SkillDescriptor) -> None:
        """Register a textual skill. Does not generate adapter yet (lazy)."""
        self.registry[descriptor.skill_id] = descriptor

    async def load(self, skill_id: str) -> LoRAAdapter:
        """
        Load skill as LoRA adapter:
          1. Check local cache (same hash = same adapter)
          2. If miss: call hypernetwork to generate
          3. Merge into model weights
          4. Return adapter handle
        """
        if skill_id in self.adapters:
            self.active.append(skill_id)
            return self.adapters[skill_id]

        descriptor = self.registry.get(skill_id)
        if not descriptor:
            raise ValueError(f"Skill '{skill_id}' not registered.")

        # Check cache
        cache_path = f"{self.cache_dir}/{descriptor.skill_hash()}.json"
        if os.path.exists(cache_path):
            with open(cache_path) as f:
                meta = json.load(f)
            adapter = LoRAAdapter(
                skill_id=skill_id, skill_hash=descriptor.skill_hash(),
                rank=meta["rank"], alpha=meta["alpha"], adapter_path=cache_path
            )
        else:
            # Generate via hypernetwork
            adapter = await self._generate_adapter(descriptor)
            # Cache metadata
            with open(cache_path, "w") as f:
                json.dump({
                    "skill_id": skill_id, "skill_hash": descriptor.skill_hash(),
                    "rank": adapter.rank, "alpha": adapter.alpha,
                    "adapter_path": adapter.adapter_path,
                }, f)

        self.adapters[skill_id]  = adapter
        self.active.append(skill_id)
        return adapter

    def unload(self, skill_id: str) -> None:
        """Unload adapter — model returns to base weights. Zero residue."""
        if skill_id in self.active:
            self.active.remove(skill_id)

    def compose(self, skill_ids: list[str], weights: list[float] | None = None) -> LoRAAdapter:
        """
        LatentSkill paper finding: skill LoRAs form structured semantic geometry.
        Composable via parameter-space arithmetic when skills are aligned.
        Weighted sum of A/B matrices → novel task adapter without retraining.

        weights = None → equal contribution
        weights = [0.7, 0.3] → dominant first skill with secondary influence
        """
        if not weights:
            weights = [1.0 / len(skill_ids)] * len(skill_ids)

        loaded = [self.adapters.get(sid) for sid in skill_ids]
        missing = [sid for sid, a in zip(skill_ids, loaded) if a is None]
        if missing:
            raise ValueError(f"Skills not loaded: {missing}. Call load() first.")

        # In production: torch.stack + weighted sum of lora_A, lora_B tensors
        # Here: metadata composition stub
        composed_id = "composed_" + "_".join(skill_ids)
        return LoRAAdapter(
            skill_id=composed_id,
            skill_hash=hashlib.sha256(composed_id.encode()).hexdigest()[:16],
            rank=max(a.rank for a in loaded if a),
            alpha=sum(a.alpha * w for a, w in zip(loaded, weights) if a),
        )

    async def _generate_adapter(self, descriptor: SkillDescriptor) -> LoRAAdapter:
        """
        Call pretrained hypernetwork to generate LoRA adapter from skill text.
        In production: POST skill_text to LatentSkill hypernetwork endpoint.
        Returns actual LoRA A/B weight tensors.
        """
        import aiohttp

        if not self.hypernetwork_url:
            # Dev mode: return stub adapter
            return LoRAAdapter(
                skill_id=descriptor.skill_id,
                skill_hash=descriptor.skill_hash(),
                rank=descriptor.lora_rank,
                alpha=descriptor.lora_alpha,
                adapter_path=f"{self.cache_dir}/{descriptor.skill_hash()}_stub",
            )

        skill_text = descriptor.to_skill_text()
        async with aiohttp.ClientSession() as s:
            async with s.post(
                f"{self.hypernetwork_url}/generate",
                json={"skill_text": skill_text, "rank": descriptor.lora_rank,
                      "alpha": descriptor.lora_alpha},
                timeout=aiohttp.ClientTimeout(total=30)
            ) as resp:
                data = await resp.json()
                # data["adapter_path"] = HF Hub path to saved adapter
                return LoRAAdapter(
                    skill_id=descriptor.skill_id,
                    skill_hash=descriptor.skill_hash(),
                    rank=descriptor.lora_rank,
                    alpha=descriptor.lora_alpha,
                    adapter_path=data.get("adapter_path", ""),
                )

    def list_active(self) -> list[str]:
        return list(self.active)

    def prefill_token_savings(self) -> dict:
        """
        Estimate token savings from weight-space vs context-space skills.
        Based on paper: 64.1% reduction on seen splits.
        """
        active_count    = len(self.active)
        avg_skill_tokens = 150  # typical textual skill length
        context_tokens  = active_count * avg_skill_tokens
        weight_tokens   = 0    # weight-space skills = zero prompt tokens
        return {
            "context_tokens_saved": context_tokens,
            "weight_tokens_used":   weight_tokens,
            "reduction_pct":        100.0 if active_count > 0 else 0.0,
            "active_skills":        self.active,
        }


